import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect, within } from 'storybook/test';
import { Badge, type BadgeProps, type BadgeColor, type BadgeSize, type BadgeType, type BadgeVariant } from './Badge';
import { baseIconNames } from '../../icons/names';
import { Showcase, Variant } from '../../docs/blocks/DocBlocks';
import componentFrame from '../../assets/design/badge/badge-component.png';
import guidelinesFrame from '../../assets/design/badge/badge-guidelines.png';

const variants: BadgeVariant[] = ['filled', 'light', 'stroke', 'text'];
const sizes: BadgeSize[] = ['md', 'sm', 'xs'];
const types: BadgeType[] = ['text', 'numeric', 'dot'];
const colors: BadgeColor[] = ['neutral', 'info', 'success', 'warning', 'error'];
const title = (word: string) => word[0].toUpperCase() + word.slice(1);

// Known contrast note: the Figma Warning colour on white and on its light fill is below 4.5:1. Listed in the Accessibility panel, not failed, until the colour is decided in Figma
const warningContrastNote = { a11y: { test: 'todo' } } as const;

const meta = {
  title: 'Components/Badge',
  // Status: ready, in-progress or draft. Shown in the page header; in-progress and draft also in the sidebar
  tags: ['ready'],
  component: Badge,
  // Badge.mdx supplies the documentation instead of an autogenerated page.
  parameters: {
    layout: 'padded',
    docs: { description: { component: 'A compact, static label, count or dot that adds status or category information beside other content.' } },
    // The Design tab: the Figma frames as images (the company's file isn't linked publicly)
    design: [
      { name: 'Component', type: 'image', url: componentFrame },
      { name: 'Guidelines', type: 'image', url: guidelinesFrame },
    ],
  },
  args: { variant: 'filled', size: 'md', type: 'text', color: 'neutral', label: 'Badge', value: '2', leftIcon: 'brightness', rightIcon: 'brightness', decorative: false, 'aria-label': '' },
  argTypes: {
    variant: { control: 'inline-radio', options: variants },
    size: { control: 'inline-radio', options: sizes },
    type: { control: 'inline-radio', options: types },
    color: { control: 'select', options: colors },
    label: { control: 'text' },
    value: { control: 'text' },
    leftIcon: { control: 'select', options: [null, ...baseIconNames], labels: { null: 'none' } },
    rightIcon: { control: 'select', options: [null, ...baseIconNames], labels: { null: 'none' } },
    decorative: { control: 'boolean' },
    'aria-label': { control: 'text', description: 'A contextual accessible name, especially for a standalone dot or count (for example, “2 unread messages”). A Dot falls back to label.' },
  },
} satisfies Meta<typeof Badge>;

export default meta;
type Story = StoryObj<typeof meta>;

const text = { font: 'var(--typo-body-md-regular)', color: 'var(--text-strong-1000)' };

export const Playground: Story = {};

/* ---- Examples: real tasks, each one a live story with a check of its behaviour ---- */

/** Payment status in a table: a Light badge with a word, so the colour is never the only cue. */
export const StatusInATable: Story = {
  name: 'Status in a table',
  render: () => (
    <table style={{ borderCollapse: 'collapse', ...text }}>
      <tbody>
        {[
          ['Invoice #1042', 'Paid', 'success'],
          ['Invoice #1043', 'Overdue', 'error'],
          ['Invoice #1044', 'Draft', 'neutral'],
        ].map(([name, status, color]) => (
          <tr key={name} style={{ borderBottom: '1px solid var(--stroke-soft-200)' }}>
            <td style={{ padding: 'var(--space-300) var(--space-800) var(--space-300) 0' }}>{name}</td>
            <td style={{ padding: 'var(--space-300) 0' }}>
              <Badge variant="light" size="sm" color={color as BadgeColor} label={status} leftIcon={null} rightIcon={null} />
            </td>
          </tr>
        ))}
      </tbody>
    </table>
  ),
  play: async ({ canvasElement }) => {
    await expect(within(canvasElement).getByText('Overdue')).toBeVisible();
  },
};

/** An unread count: the badge is named by what it counts, not just the number. */
export const UnreadCount: Story = {
  name: 'Unread count',
  render: () => (
    <span style={{ display: 'inline-flex', alignItems: 'center', gap: 'var(--space-200)', ...text }}>
      Messages <Badge type="numeric" color="error" size="sm" value={12} aria-label="12 unread messages" />
    </span>
  ),
  play: async ({ canvasElement }) => {
    await expect(within(canvasElement).getByRole('img', { name: '12 unread messages' })).toBeVisible();
  },
};

/** A dot next to a written status: the text says it, so the dot is hidden from screen readers. */
export const DotNextToAStatus: Story = {
  name: 'Dot next to a status',
  render: () => (
    <div style={{ display: 'grid', gap: 'var(--space-300)', ...text }}>
      <span style={{ display: 'inline-flex', alignItems: 'center', gap: 'var(--space-100)' }}><Badge type="dot" color="success" decorative />Available</span>
      <span style={{ display: 'inline-flex', alignItems: 'center', gap: 'var(--space-100)' }}><Badge type="dot" color="neutral" decorative />Offline</span>
    </div>
  ),
  play: async ({ canvasElement }) => {
    await expect(within(canvasElement).queryAllByRole('img')).toHaveLength(0);
  },
};

/** A long label wraps inside its parent and the badge grows; prefer a short word people can scan. */
export const ALongLabel: Story = {
  name: 'A long label',
  args: { label: 'Awaiting additional verification documents' },
  render: (args: BadgeProps) => <div style={{ width: 'calc(var(--space-2000) * 2)', maxWidth: '100%' }}><Badge {...args} type="text" /></div>,
};

/* ---- Overview ---- */

/** Text, Numeric and Dot. */
export const Types: Story = {
  render: (args: BadgeProps) => (
    <Showcase>{types.map(type => <Variant key={type} caption={title(type)}><Badge {...args} type={type} /></Variant>)}</Showcase>
  ),
};

/** Filled, Light, Stroke and Text. */
export const Styles: Story = {
  render: (args: BadgeProps) => (
    <Showcase>{variants.map(variant => <Variant key={variant} caption={title(variant)}><Badge {...args} variant={variant} /></Variant>)}</Showcase>
  ),
};

/** Neutral, Info, Success, Warning and Error, in the four styles. */
export const Colors: Story = {
  parameters: warningContrastNote,
  render: (args: BadgeProps) => (
    <Showcase>
      {colors.map(color => (
        <Variant key={color} caption={title(color)}>
          <div style={{ display: 'grid', gap: 'var(--space-200)', justifyItems: 'center' }}>
            {variants.map(variant => <Badge key={variant} {...args} color={color} variant={variant} />)}
          </div>
        </Variant>
      ))}
    </Showcase>
  ),
};

/** md-24, sm-20 and xs-16, for each type. */
export const Sizes: Story = {
  render: (args: BadgeProps) => (
    <Showcase>
      {sizes.map(size => (
        <Variant key={size} caption={{ md: 'md · 24px', sm: 'sm · 20px', xs: 'xs · 16px' }[size]}>
          {types.map(type => <Badge key={type} {...args} type={type} size={size} />)}
        </Variant>
      ))}
    </Showcase>
  ),
};
