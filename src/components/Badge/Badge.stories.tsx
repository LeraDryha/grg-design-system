import type { CSSProperties } from 'react';
import type { Meta, StoryObj } from '@storybook/react-vite';
import { Badge, type BadgeProps, type BadgeColor, type BadgeSize, type BadgeType, type BadgeVariant } from './Badge';
import { baseIconNames } from '../../icons/names';
import { Anatomy as AnatomyBlock } from '../../docs/blocks/DocBlocks';

const variants: BadgeVariant[] = ['filled', 'light', 'stroke', 'text'];
const sizes: BadgeSize[] = ['md', 'sm', 'xs'];
const types: BadgeType[] = ['text', 'numeric', 'dot'];
const colors: BadgeColor[] = ['neutral', 'info', 'success', 'warning', 'error'];

const meta = {
  title: 'Components/Badge',
  component: Badge,
  // Badge.mdx supplies the documentation instead of an autogenerated page.
  parameters: { layout: 'padded', docs: { description: { component: 'A compact, static label, count or dot that adds status or category information beside other content.' } } },
  args: { variant: 'filled', size: 'md', type: 'text', color: 'neutral', label: 'Badge', value: '2', leftIcon: 'brightness', rightIcon: 'brightness', decorative: false, 'aria-label': '' },
  argTypes: {
    variant: { control: 'inline-radio', options: variants },
    size: { control: 'inline-radio', options: sizes },
    type: { control: 'inline-radio', options: types },
    color: { control: 'select', options: colors },
    label: { control: 'text' },
    value: { control: 'text' },
    leftIcon: { control: 'select', options: [null, ...baseIconNames], labels: { null: 'none' } },
    rightIcon: { control: 'select', options: [null, ...baseIconNames], labels: { null: 'none' } },
    decorative: { control: 'boolean' },
    'aria-label': { control: 'text', description: 'A contextual accessible name, especially for a standalone dot or count (for example, “2 unread messages”). A Dot falls back to label.' },
  },
} satisfies Meta<typeof Badge>;

export default meta;
type Story = StoryObj<typeof meta>;

const row: CSSProperties = { display: 'flex', flexWrap: 'wrap', alignItems: 'center', gap: 'var(--space-600)', maxWidth: '100%' };
const column: CSSProperties = { display: 'grid', justifyItems: 'start', gap: 'var(--space-600)', maxWidth: '100%' };
const caption: CSSProperties = { margin: 0, color: 'var(--text-subtle-700)', font: 'var(--typo-body-sm-medium)', textTransform: 'capitalize' };

export const Playground: Story = {};

export const Anatomy: Story = {
  render: (args: BadgeProps) => <AnatomyBlock width="auto" markers={[
    { n: 1, target: '[data-type="text"]', side: 'left' },
    { n: 2, target: '.grg-badge__left-icon', side: 'top' },
    { n: 3, target: '.grg-badge__label', side: 'top' },
    { n: 4, target: '.grg-badge__value', side: 'bottom' },
    { n: 5, target: '.grg-badge__dot', side: 'bottom' },
  ]}><div style={row}>{types.map(type => <Badge key={type} {...args} type={type} />)}</div></AnatomyBlock>,
};

export const Types: Story = {
  render: (args: BadgeProps) => <div style={row}>{types.map(type => <Badge key={type} {...args} type={type} />)}</div>,
};

export const Sizes: Story = {
  render: (args: BadgeProps) => <div style={column}>{types.map(type => <div key={type} style={row}>{sizes.map(size => <Badge key={size} {...args} type={type} size={size} />)}</div>)}</div>,
};

export const Styles: Story = {
  render: (args: BadgeProps) => <div style={row}>{variants.map(variant => <Badge key={variant} {...args} variant={variant} />)}</div>,
};

export const Colors: Story = {
  render: (args: BadgeProps) => <div style={row}>{colors.map(color => <Badge key={color} {...args} color={color} />)}</div>,
};

/** All 180 Figma variants. Rows follow Figma: style, then colour; groups are md, sm and xs. */
export const AllVariants: Story = {
  render: (args: BadgeProps) => <div style={{ ...column, gap: 'var(--space-1200)' }}>{variants.map(variant =>
    <section key={variant} style={column} aria-label={variant}>
      <h3 style={caption}>{variant}</h3>
      {colors.map(color => <div key={color} style={row}>
        <span style={{ ...caption, width: 'var(--space-2000)' }}>{color}</span>
        {sizes.map(size => <div key={size} style={{ ...row, gap: 'var(--space-400)' }}>{types.map(type => <Badge key={type} {...args} variant={variant} size={size} color={color} type={type} />)}</div>)}
      </div>)}
    </section>)}</div>,
};

/** Each side can use a Base icon independently; Numeric and Dot never show these icons. */
export const Icons: Story = {
  render: (args: BadgeProps) => <div style={row}>
    <Badge {...args} type="text" rightIcon={null} />
    <Badge {...args} type="text" leftIcon={null} />
    <Badge {...args} type="text" />
    <Badge {...args} type="text" leftIcon={null} rightIcon={null} />
  </div>,
};

export const NumericValues: Story = {
  render: (args: BadgeProps) => <div style={row}>{[0, args.value, 24, '99+'].map((value, index) => <Badge key={index} {...args} type="numeric" value={value} aria-label={`${value} unread messages`} />)}</div>,
};

export const DotLabels: Story = {
  args: { type: 'dot', color: 'success', variant: 'light', label: 'Available' },
  render: (args: BadgeProps) => <div style={row}>
    <Badge {...args} type="dot" />
    <span style={{ ...row, gap: 'var(--space-100)' }}><Badge {...args} type="dot" decorative />{args.label}</span>
  </div>,
};

export const LongLabel: Story = {
  args: { label: 'Awaiting additional verification documents' },
  render: (args: BadgeProps) => <div style={{ width: 'calc(var(--space-2000) * 2)', maxWidth: '100%' }}><Badge {...args} type="text" /></div>,
};
