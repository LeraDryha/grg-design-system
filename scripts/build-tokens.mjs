// Builds the CSS tokens and the token data for the docs from the Figma export in figma/.
// Figma is the source of truth: re-export figma/variables.json and figma/styles.json, then run `npm run tokens`.
//
// Naming, one rule per layer, so every CSS variable maps back to exactly one Figma variable or style:
//   primitive colour  gold/500                  → --color-gold-500
//   semantic colour   Text/text-strong-1000     → --text-strong-1000
//   spacing           Spasing/100               → --space-100
//   corner radius     Corner/md-10              → --radius-md-10
//   typography        font/size/14              → --font-size-14
//   text style        Body-md/Semibold          → --typo-body-md-semibold (+ --typo-…-tracking)
//   effect style      Elevation/Light/md        → --shadow-md (the Dark style under [data-theme='dark'])
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const variables = JSON.parse(readFileSync(new URL('figma/variables.json', root)));
const styles = JSON.parse(readFileSync(new URL('figma/styles.json', root)));

// White-label palettes live in the same Figma file but are not part of this system (gold and dark themes only).
const WHITE_LABEL = ['linen', 'dark pink', 'dark green', 'dark blue', 'dark red', 'dark orange', 'bashful pink'];

const slug = s => s.trim().toLowerCase().replace(/\s+/g, '-');
const isPrimitive = name => !name.includes('/') ? false : /^[a-z ]+\/\d+$/.test(name);
const colorVar = name => (isPrimitive(name) ? `--color-${slug(name.replace('/', '-'))}` : `--${slug(name.split('/').pop())}`);

// ---- Colours ----
const colors = variables.Colors.map(line => {
  const [name, , light, dark] = line.split('|');
  return { name, light, dark };
}).filter(c => !WHITE_LABEL.some(p => c.name.startsWith(p + '/')));

const valueOf = v => (v.startsWith('->') ? `var(${colorVar(v.replace('->Colors:', ''))})` : v);
const primitives = colors.filter(c => isPrimitive(c.name));
const semantic = colors.filter(c => !isPrimitive(c.name));

const lightLines = [...primitives, ...semantic].map(c => `  ${colorVar(c.name)}: ${valueOf(c.light)};`);
const darkLines = [...primitives, ...semantic].filter(c => c.light !== c.dark).map(c => `  ${colorVar(c.name)}: ${valueOf(c.dark)};`);

// ---- Spacing, radius, typography variables ----
const space = variables.Spasing.map(l => l.split('|')).filter(([, t]) => t === 'F').map(([n, , v]) => `  --space-${n}: ${v}px;`);
const radius = variables.Corner.map(l => l.split('|')).map(([n, , v]) => `  --radius-${slug(n)}: ${v}px;`);
const WEIGHTS = { regular: 400, medium: 500, semibold: 600, bold: 700 };
const typeVars = variables.Typography.map(l => l.split('|')).map(([n, , v]) => {
  const [, group, key] = n.split('/');
  if (group === 'family') return `  --font-family-${key}: '${v}', system-ui, sans-serif;`;
  if (group === 'weight') return `  --font-weight-${slug(key)}: ${WEIGHTS[slug(key)]};`;
  return `  --font-${group}-${key}: ${v}px;`;
});

// ---- Text styles ----
// Display styles (Bounded, marketing headlines) are not part of this system and are skipped.
// Code styles use Fira Code, which has no family variable in Figma, so its family is written here,
// the only place raw values are allowed.
const SKIPPED_FAMILIES = ['Bounded'];
const FAMILY = { 'Nunito Sans': 'var(--font-family-body)', 'Fira Code': "'Fira Code', ui-monospace, monospace" };
const weightOf = style => `var(--font-weight-${slug(style)})`;
const textStyles = styles.text.filter(s => !SKIPPED_FAMILIES.includes(s.family)).map(s => {
  const id = slug(s.name.replace(/\//g, '-'));
  const style = s.style === 'SemiBold' ? 'semibold' : s.style;
  const size = `var(--font-size-${s.size}, ${s.size}px)`;
  const lh = `var(--font-line-height-${s.lh.value}, ${s.lh.value}px)`;
  const tracking = s.ls.value ? `${+(s.ls.value / 100).toFixed(4)}em` : '0';
  return { id, name: s.name, family: s.family, weight: WEIGHTS[slug(style)], size: s.size, lineHeight: s.lh.value, tracking,
    css: [`  --typo-${id}: ${weightOf(style)} ${size}/${lh} ${FAMILY[s.family]};`, `  --typo-${id}-tracking: ${tracking};`] };
});

// ---- Effects ----
const shadowOf = effects => effects.map(e => `${e.type === 'INNER_SHADOW' ? 'inset ' : ''}${e.x}px ${e.y}px ${e.blur}px ${e.spread}px ${e.color}`).join(', ');
const effects = { light: [], dark: [], blur: [] };
for (const s of styles.effects) {
  const parts = s.name.split('/');
  if (parts[0] === 'Elevation') effects[slug(parts[1])].push(`  --shadow-${parts[2]}: ${shadowOf(s.effects)};`);
  if (parts[0] === 'Table Shadow') effects[slug(parts[2])].push(`  --shadow-table-${slug(parts[1])}: ${shadowOf(s.effects)};`);
  if (parts[0] === 'Blur' && parts[1] === 'Light') effects.blur.push(`  --blur-${parts[2]}: ${s.effects[0].blur}px;`);
}

const css = `/* Generated by scripts/build-tokens.mjs from the Figma export in figma/. Do not edit by hand: run \`npm run tokens\`. */

:root {
  color-scheme: light;

  /* Primitive colours: raw values. Components never use them directly. */
${lightLines.slice(0, primitives.length).join('\n')}

  /* Semantic colours: what components use. They point at primitives and swap in the dark theme. */
${lightLines.slice(primitives.length).join('\n')}

  /* Spacing */
${space.join('\n')}

  /* Corner radius */
${radius.join('\n')}

  /* Typography */
${typeVars.join('\n')}

  /* Text styles: use as \`font: var(--typo-…)\` with \`letter-spacing: var(--typo-…-tracking)\` */
${textStyles.flatMap(t => t.css).join('\n')}

  /* Elevation and blur */
${effects.light.join('\n')}
${effects.blur.join('\n')}
}

[data-theme='dark'] {
  color-scheme: dark;
${darkLines.join('\n')}
${effects.dark.join('\n')}
}
`;

mkdirSync(new URL('src/tokens/', root), { recursive: true });
writeFileSync(new URL('src/styles/tokens.css', root), css);

// Data for the Foundations pages
const resolve = (v, mode) => (v.startsWith('->') ? resolve(colors.find(c => c.name === v.slice(9))[mode], mode) : v);
const data = {
  semantic: semantic.map(c => ({ figma: c.name, css: colorVar(c.name), light: c.light.replace('->Colors:', ''), dark: c.dark.replace('->Colors:', ''), lightHex: resolve(c.light, 'light'), darkHex: resolve(c.dark, 'dark') })),
  primitives: primitives.map(c => ({ figma: c.name, css: colorVar(c.name), hex: c.light })),
  space: variables.Spasing.map(l => l.split('|')).filter(([, t]) => t === 'F').map(([n, , v]) => ({ figma: `Spasing/${n}`, css: `--space-${n}`, px: +v })),
  radius: variables.Corner.map(l => l.split('|')).map(([n, , v]) => ({ figma: `Corner/${n}`, css: `--radius-${slug(n)}`, px: +v })),
  text: textStyles.map(({ css, ...t }) => ({ ...t, css: `--typo-${t.id}` })),
  shadows: styles.effects.filter(s => s.name.startsWith('Elevation/Light')).map(s => ({ figma: s.name.replace('/Light', ''), css: `--shadow-${s.name.split('/')[2]}` })),
};
writeFileSync(new URL('src/tokens/tokens.json', root), JSON.stringify(data, null, 1) + '\n');

console.log(`tokens.css: ${primitives.length} primitive and ${semantic.length} semantic colours (${darkLines.length} dark overrides), ${space.length} spacing, ${radius.length} radius, ${textStyles.length} text styles`);
