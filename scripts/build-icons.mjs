// Builds the icon set from the Figma export in figma/icons.json (Figma "Base icons", node 23:11109).
// Re-export the icons, then run `npm run icons`. Writes one SVG per icon to src/icons/base/ and the
// list of names to src/icons/names.ts. The Figma name becomes the file name: "calendar 01" → calendar-01.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const { icons } = JSON.parse(readFileSync(new URL('figma/icons.json', root)));
const slug = name => name.trim().toLowerCase().replace(/\s+/g, '-');

const dir = new URL('src/icons/base/', root);
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });

// Paths are single-colour: icons are drawn as a CSS mask, so only the shape matters, the colour comes from the token.
const path = d => {
  const evenOdd = d.startsWith('E');
  const body = evenOdd ? d.slice(1) : d;
  const stroke = /^S([\d.]+)\|/.exec(body);
  if (stroke) {
    return `<path d="${body.slice(stroke[0].length)}" fill="none" stroke="#000" stroke-width="${stroke[1]}" stroke-linecap="round" stroke-linejoin="round"/>`;
  }
  return `<path d="${body}" fill="#000"${evenOdd ? ' fill-rule="evenodd" clip-rule="evenodd"' : ''}/>`;
};

const names = [];
for (const [name, paths] of Object.entries(icons)) {
  const file = slug(name);
  if (names.includes(file)) throw new Error(`Two icons are both called ${file}`);
  names.push(file);
  writeFileSync(new URL(`${file}.svg`, dir), `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">${paths.map(path).join('')}</svg>\n`);
}
names.sort();

writeFileSync(
  new URL('src/icons/names.ts', root),
  `// Generated by scripts/build-icons.mjs from figma/icons.json. Do not edit by hand: run \`npm run icons\`.\n\n` +
    `/** Every icon of the Figma "Base icons" set, by its Figma name (spaces become hyphens). */\n` +
    `export const baseIconNames = [\n${names.map(n => `  '${n}',`).join('\n')}\n] as const;\n\n` +
    `export type BaseIconName = (typeof baseIconNames)[number];\n`,
);

console.log(`icons: ${names.length} base icons`);

// Social icons from figma/social-icons.json (Figma "Social icon", node 68:17086): Platform × Style.
// Writes src/icons/social/<platform>-brand.svg, <platform>-gray.svg and the names to src/icons/social-names.ts.
// "X (Twitter)" → x. Gray icons are single-colour (drawn as a CSS mask, the colour comes from the token).
// Brand icons keep their brand colours. Near-black brand marks also get a -dark file with the black turned
// white, so they stay visible in the dark theme; Figma has no dark brand set.
const social = JSON.parse(readFileSync(new URL('figma/social-icons.json', root))).icons;
const socialSlug = name => name.replace(/\s*\(.*\)/, '').trim().toLowerCase().replace(/\s+/g, '-');
const socialDir = new URL('src/icons/social/', root);
rmSync(socialDir, { recursive: true, force: true });
mkdirSync(socialDir, { recursive: true });

const NEAR_BLACK = /fill="(black|#000000|#242E36|#001935|#111827)"/g;
// Snapchat and Notion draw a black outline around a white shape: they read fine on dark as they are.
const OUTLINED = ['snapchat', 'notion'];
const svgOf = body => `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">${body}</svg>\n`;

const platforms = [];
const labels = {};
const gray = [];
const darkMarks = [];
for (const [key, body] of Object.entries(social)) {
  const [platform, style] = key.split('|');
  const file = socialSlug(platform);
  if (!platforms.includes(file)) {
    platforms.push(file);
    labels[file] = platform;
  }
  if (style === 'Gray') {
    gray.push(file);
    writeFileSync(new URL(`${file}-gray.svg`, socialDir), svgOf(body.replaceAll('#737373', '#000')));
    continue;
  }
  writeFileSync(new URL(`${file}-brand.svg`, socialDir), svgOf(body));
  if (!OUTLINED.includes(file) && NEAR_BLACK.test(body)) {
    darkMarks.push(file);
    writeFileSync(new URL(`${file}-brand-dark.svg`, socialDir), svgOf(body.replace(NEAR_BLACK, 'fill="white"')));
  }
  NEAR_BLACK.lastIndex = 0;
}

const list = arr => `[\n${arr.map(n => `  '${n}',`).join('\n')}\n] as const`;
writeFileSync(
  new URL('src/icons/social-names.ts', root),
  `// Generated by scripts/build-icons.mjs from figma/social-icons.json. Do not edit by hand: run \`npm run icons\`.\n\n` +
    `/** Every platform of the Figma "Social icon" set, in Figma order. */\n` +
    `export const socialPlatforms = ${list(platforms)};\n\n` +
    `export type SocialPlatform = (typeof socialPlatforms)[number];\n\n` +
    `/** Platforms that also have the Gray style in Figma. */\n` +
    `export const grayPlatforms = ${list(gray)} satisfies readonly SocialPlatform[];\n\n` +
    `export type GrayPlatform = (typeof grayPlatforms)[number];\n\n` +
    `/** Brand marks that are near-black in Figma; they turn white in the dark theme. */\n` +
    `export const darkMarkPlatforms = ${list(darkMarks)} satisfies readonly SocialPlatform[];\n\n` +
    `/** Figma Platform names. */\n` +
    `export const platformLabels: Record<SocialPlatform, string> = ${JSON.stringify(labels, null, 2).replace(/"([a-z-]+)":/g, "'$1':").replace(/"/g, "'")};\n`,
);

console.log(`icons: ${platforms.length} social platforms, ${gray.length} in gray, ${darkMarks.length} with a dark-theme mark`);

// Coin, Payment method and Country icons from figma/<set>-icons.json (see scripts/split-figma-export.py).
// Full-colour pictures, drawn as images. Writes src/icons/<set>/<key>.svg and src/icons/<set>-names.ts.
// Key: the Figma name in lower case, anything other than letters and digits becomes a hyphen
// ("Bitcoin (BTC)" → bitcoin-btc, "Shop Pay" → shop-pay, "UA" → ua). Duplicates in Figma get -2, -3.
const keyOf = name => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const pictureSets = [
  // Coins on a black disc would disappear on the dark theme: they also get a -dark file with black and white swapped
  { set: 'coin', type: 'CoinName', list: 'coinNames', what: 'Coin', darkDiscs: true },
  { set: 'payment', type: 'PaymentMethod', list: 'paymentMethods', what: 'Payment method icon' },
  // Not shown in the Storybook, by decision of the design system owner
  { set: 'country', type: 'CountryCode', list: 'countryCodes', what: 'Country icon', skip: ['RU', 'BY'] },
];

const HEX = { black: '#000000', white: '#ffffff' };
const luminance = color => {
  let h = (HEX[color] ?? color).slice(1);
  if (h.length === 3) h = [...h].map(c => c + c).join('');
  const [r, g, b] = [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16) / 255).map(c => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const FILL = /fill="(#[0-9A-Fa-f]{3,6}|black|white)"/g;
const PAINT = /(fill|stroke)="(#[0-9A-Fa-f]{3,6}|black|white)"/g;
const COLOR = /(?:fill|stroke|stop-color)="(#[0-9A-Fa-f]{3,6}|black|white)"/g;
const contrast = (a, b) => (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
// The first shape is the coin's disc. When it is near-black, the dark version swaps near-black and white
// fills and strokes (outside masks and <defs>), so the disc turns white. Skipped when another colour of the logo would be
// hard to see on white (under 3:1): such a coin stays as it is, its light logo reads on dark anyway.
const darkVersion = svg => {
  const [body, defs = ''] = svg.split('<defs>');
  const first = FILL.exec(body);
  FILL.lastIndex = 0;
  if (!first || luminance(first[1]) >= 0.03) return null;
  const others = [...svg.matchAll(COLOR)].map(m => luminance(m[1])).filter(l => l >= 0.03 && l <= 0.9);
  if (others.some(l => contrast(l, 1) < 3)) return null;
  const swap = part =>
    part.replace(PAINT, (m, attr, c) => {
      const l = luminance(c);
      if (l < 0.03) return `${attr}="#ffffff"`;
      if (l > 0.9) return `${attr}="${HEX[first[1]] ?? first[1]}"`;
      return m;
    });
  const swapped = body.split(/(<mask[\s\S]*?<\/mask>)/).map(part => (part.startsWith('<mask') ? part : swap(part))).join('');
  return defs ? `${swapped}<defs>${defs}` : swapped;
};

for (const { set, type, list, what, darkDiscs = false, skip = [] } of pictureSets) {
  const { icons: source } = JSON.parse(readFileSync(new URL(`figma/${set}-icons.json`, root)));
  const out = new URL(`src/icons/${set}/`, root);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const entries = [];
  const dark = [];
  for (const [name, svgs] of Object.entries(source)) {
    if (skip.includes(name)) continue;
    svgs.forEach((svg, i) => {
      let key = keyOf(name) + (i ? `-${i + 1}` : '');
      while (entries.some(e => e.key === key)) key += '-2';
      entries.push({ key, label: name + (i ? ` (${i + 1})` : '') });
      writeFileSync(new URL(`${key}.svg`, out), svg + '\n');
      const onDark = darkDiscs && darkVersion(svg);
      if (onDark) {
        dark.push(key);
        writeFileSync(new URL(`${key}-dark.svg`, out), onDark + '\n');
      }
    });
  }
  writeFileSync(
    new URL(`src/icons/${set}-names.ts`, root),
    `// Generated by scripts/build-icons.mjs from figma/${set}-icons.json. Do not edit by hand: run \`npm run icons\`.\n\n` +
      `/** Every icon of the Figma "${what}" set, in Figma order: key and Figma name. */\n` +
      `export const ${list} = [\n${entries.map(e => `  ['${e.key}', ${JSON.stringify(e.label)}],`).join('\n')}\n] as const;\n\n` +
      `export type ${type} = (typeof ${list})[number][0];\n` +
      (darkDiscs
        ? `\n/** Icons on a near-black disc: they have a -dark file with black and white swapped, for the dark theme. */\n` +
          `export const ${set}DarkVersions: readonly ${type}[] = [\n${dark.map(k => `  '${k}',`).join('\n')}\n];\n`
        : ''),
  );
  console.log(`icons: ${entries.length} ${set} icons${darkDiscs ? `, ${dark.length} with a dark-theme version` : ''}`);
}
